"""Collect every tag used in the BDD feature files and publish it.

Writes BDD_TAGS.md (repo root) and rewrites the tag dropdown of
.github/workflows/bdd-run-by-tag.yml between its BEGIN/END markers.

A tag is "unavailable" when none of its scenarios can execute (every scenario
sits in a *_pending.feature). GitHub choice inputs cannot disable an option, so
the reason is shown in the option text and the run workflow refuses it.

Usage: python tools/update_bdd_tags.py
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ROOT / "refua_tests" / "bdd" / "features"
TAGS_FILE = ROOT / "BDD_TAGS.md"
WORKFLOW = ROOT / ".github" / "workflows" / "bdd-run-by-tag.yml"
BEGIN = "# BEGIN BDD TAG OPTIONS"
END = "# END BDD TAG OPTIONS"
SCENARIO = re.compile(r"^\s*Scenario( Outline)?:")
TAG_LINE = re.compile(r"^\s*(@\S+(\s+@\S+)*)\s*$")


def collect() -> dict[str, dict]:
    tags: dict[str, dict] = defaultdict(lambda: {"total": 0, "runnable": 0, "features": set()})
    for feature in sorted(FEATURES.glob("*.feature")):
        pending = feature.stem.endswith("_pending")
        feature_tags: list[str] = []
        pending_tags: list[str] = []
        in_feature = False
        for line in feature.read_text(encoding="utf-8-sig").splitlines():
            match = TAG_LINE.match(line)
            if match:
                pending_tags += [t[1:] for t in match.group(1).split()]
            elif line.strip().startswith("Feature:"):
                feature_tags, pending_tags, in_feature = pending_tags, [], True
            elif in_feature and SCENARIO.match(line):
                for tag in set(feature_tags + pending_tags):
                    tags[tag]["total"] += 1
                    tags[tag]["runnable"] += 0 if pending else 1
                    tags[tag]["features"].add(feature.name)
                pending_tags = []
    return dict(tags)


def reason(info: dict) -> str | None:
    if info["runnable"] == 0:
        return f"all {info['total']} scenarios pending clarification"
    return None


def option(tag: str, info: dict) -> str:
    why = reason(info)
    return tag if why is None else f"{tag} — unavailable: {why}"


def write_tags_file(tags: dict[str, dict]) -> None:
    lines = [
        "# BDD Tags",
        "",
        "Generated by `tools/update_bdd_tags.py` (daily 05:00 Israel time, or GitHub:",
        "**Actions → BDD - Update tag list → Run workflow**). Do not edit by hand.",
        "Run a tag from GitHub: **Actions → BDD - Run by tag → Run workflow**.",
        "",
        "| Tag | Scenarios | Runnable | Status | Feature files |",
        "|---|---:|---:|---|---|",
    ]
    for tag in sorted(tags, key=lambda t: (reason(tags[t]) is not None, t)):
        info = tags[tag]
        status = "available" if reason(info) is None else f"unavailable: {reason(info)}"
        files = sorted(info["features"])
        files = ", ".join(files) if len(files) <= 3 else f"{len(files)} feature files"
        lines.append(f"| `@{tag}` | {info['total']} | {info['runnable']} | {status} | {files} |")
    TAGS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def update_workflow(tags: dict[str, dict]) -> None:
    text = WORKFLOW.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END)
    indent = text[text.rindex("\n", 0, start) + 1:start]
    ordered = sorted(tags, key=lambda t: (reason(tags[t]) is not None, t))
    block = [BEGIN + " (generated by tools/update_bdd_tags.py - do not edit by hand)", "options:"]
    block += [f'  - "{option(tag, tags[tag])}"' for tag in ordered]
    rendered = ("\n" + indent).join(block) + "\n" + indent
    WORKFLOW.write_text(text[:start] + rendered + text[end:], encoding="utf-8")


def main() -> None:
    tags = collect()
    write_tags_file(tags)
    update_workflow(tags)
    unavailable = sum(reason(i) is not None for i in tags.values())
    print(f"{len(tags)} tags ({unavailable} unavailable) -> {TAGS_FILE.name}, {WORKFLOW.name}")


if __name__ == "__main__":
    main()
